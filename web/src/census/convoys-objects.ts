const passenger = (
  key: string,
  tab: string,
  carrier: string,
  states: string,
  population: string,
  window: [string, string],
  signature: string,
): CensusObject => ({
  key,
  tab,
  rule: HAT_B,
  title: `Glider with passenger, ${tab.replace('′', '')} states`,
  kind: `${carrier} with four or five cells attached behind it.`,
  ...object(key),
  facts: [
    ['composition', `${carrier.replace(/^Hat B's /, '')} + passenger of 4–5 cells`],
    ['states', states],
    ['attached', 'in every state'],
    ['population', population],
    hatWindow(...window),
    HAT_SPEED,
    sig(signature),
    objectRecordFact(key),
  ],
});

